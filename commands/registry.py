from .command_dispatcher import CommandDispatcher
from services.backup_services import BackupService
from console_utils import MessageLevel

def build_dispatcher(db_client, messenger,  storage_type: str = "local"):
    dispatcher = CommandDispatcher(storage_type = storage_type)
    backup_service = BackupService(db_client)
    
    def help_command(parsed_args):
        messenger.section_header("Database Backup Utility")
        messenger.success("Interactive console commands:")
        print()

        messenger.print_colored("1) Full database backup", MessageLevel.INFO)
        print("   Command:")
        print("     full database -path <destination_path> [-single-archive true|false] [-validate-restore true|false]")
        print("   Examples:")
        print("     full database -path /backups/postgres")
        print("     full database -path /backups/postgres -single-archive false")
        print("     full database -path /backups/postgres -validate-restore true")
        print("   Details:")
        print("     - Creates a physical full backup for the connected database.")
        print("     - PostgreSQL uses pg_basebackup.")
        print("     - MySQL uses xtrabackup.")
        print("     - By default, also creates a single .tar.zst archive for easier storage/upload.")
        print("     - PostgreSQL full backups run an automated temporary restore validation by default.")
        print()

        messenger.print_colored("2) Differential backup", MessageLevel.INFO)
        print("   Command:")
        print("     differential backup")
        print("   Example:")
        print("     differential backup")
        print("   Details:")
        print("     - Uses the last full backup recorded in backup_catalog.db as the base.")
        print("     - PostgreSQL copies and validates archived WAL segments.")
        print("     - PostgreSQL requires archive_mode=on and archive_command configured.")
        print("     - MySQL runs xtrabackup --incremental against the last full backup.")
        print("     - Writes metadata.json and validation.json for the backup contract.")
        print()

        messenger.print_colored("3) Execute SQL", MessageLevel.INFO)
        print("   Command:")
        print("     SQL <your_sql_query>")
        print("   Examples:")
        print("     SQL SELECT * FROM users WHERE id < 100")
        print("     SQL SELECT count(*) FROM orders")
        print("   Details:")
        print("     - Prints a short preview of returned rows in the console.")
        print("     - Statements that do not return rows are executed without preview output.")
        print()

        messenger.print_colored("4) SQL export to CSV", MessageLevel.INFO)
        print("   Command:")
        print("     SQL <your_sql_query> -extract -path <destination_path>")
        print("   Example:")
        print("     SQL SELECT * FROM users -extract -path /tmp/exports")
        print("   Details:")
        print("     - Runs the query and writes the result to CSV files under the destination path.")
        print()

        messenger.print_colored("5) PostgreSQL restore", MessageLevel.INFO)
        print("   Commands:")
        print("     restore -path <full_backup_dir_or_archive> -data-dir <new_data_dir> -wal-path <wal_archive_dir>")
        print("     restore -backup-path <full_backup_dir_or_archive> -data-dir <new_data_dir> -archive-dir <wal_archive_dir>")
        print("     restore -target-time \"2026-05-04 12:30:00\" -data-dir <new_data_dir> -wal-path <wal_archive_dir>")
        print("   Optional flags:")
        print("     -target-time <timestamp>   PITR target time; values without timezone are UTC")
        print("     -catalog-path <path>       Catalog path for PITR base backup selection, default: backup_catalog.db")
        print("     -restore-port <port>       Port for the restored PostgreSQL instance, default: 55432")
        print("     -verify-user <user>        User for the post-restore verification query")
        print("     -verify-query <sql>        Verification SQL, default: SELECT 1;")
        print("     -pg-bin-dir <directory>    Directory containing pg_ctl and psql if they are not in PATH")
        print("   Example:")
        print("     restore -path /backups/full_pg_20260427 -data-dir /tmp/pg-restore -wal-path /var/lib/postgresql/wal_archive")
        print("   Details:")
        print("     - Restore is currently implemented only for PostgreSQL.")
        print("     - The backup path can be a full backup directory or a .tar.zst archive.")
        print("     - The restore flow extracts base.tar.gz and pg_wal.tar.gz, writes recovery.signal,")
        print("       replays WAL through restore_command, starts PostgreSQL, and verifies it with SQL.")
        print("     - With -target-time, recovery_target_time is normalized to UTC and recovery_target_action=promote is written.")
        print("     - -wal-path/-archive-dir must point to the WAL archive directory, not one WAL file.")
        print()

        messenger.print_colored("6) Common flags", MessageLevel.INFO)
        print("   -path <path>                 Backup destination or SQL export destination")
        print("   -backup-path <path>          Alias-style restore input path for PostgreSQL restore")
        print("   -data-dir <path>             New PostgreSQL data directory for restore")
        print("   -wal-path <path>             PostgreSQL WAL archive directory")
        print("   -archive-dir <path>          Alias for -wal-path")
        print("   -target-time <timestamp>     PostgreSQL PITR target time; no timezone means UTC")
        print("   -catalog-path <path>         Backup catalog for PITR lookup")
        print("   -compress true|false         Compression flag used by supported backup flows")
        print("   -single-archive true|false   Create a single .tar.zst archive for full backups")
        print("   -validate-restore true|false Run PostgreSQL full backup test-restore validation")
        print("   -restore-validation-port <p> Port for validation restore, 0 chooses a free port")
        print("   -restore-validation-checksums true|false Compare per-table restore checksums")
        print("   -extract                     Export SQL result to CSV instead of previewing it")
        print()

        messenger.print_colored("7) Session commands", MessageLevel.INFO)
        print("   help                         Show this help")
        print("   exit | quit                  Leave the interactive console")
        print()
    
    dispatcher.register_command("full_backup", backup_service.full_backup)
    dispatcher.register_command("differential_backup", backup_service.differential_backup)
    dispatcher.register_command("restore_postgres", backup_service.restore_postgres)
    dispatcher.register_command("execute_sql", backup_service.execute_sql)
    dispatcher.register_command("help", help_command)
    
    return dispatcher
